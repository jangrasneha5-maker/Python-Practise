# strings are immutable i.e you cannot change then by 
# by using functions

name="sneha"#order is {0,1,2,3,4} or(-5,-4-3,-2,-1)
# string slicing
nameshort=name[0:3]#start from index 0 all the way till 3 excluding 3
print(nameshort)
nameshort=name[1:3]
print(nameshort) 
nameshort=name[:3] # this is same as 0:3
print(nameshort)
nameshort=name[1:]# same as 1:-1 i.e 1 and the last order 
print(nameshort)